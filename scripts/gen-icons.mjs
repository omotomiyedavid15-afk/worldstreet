/* Generates components/icons/atlas.generated.ts from Atlas Icons
   (@vectoricons/atlas-icons-react, ISC). The package is one 3 MB module that can't be
   tree-shaken, so only the icons listed in components/icons/icons.json are written out,
   as plain SVG markup.

   Each Atlas SVG carries a fixed id and an inline <style> block; rendering an icon
   twice would duplicate the id (an axe failure). The class rules are inlined as
   attributes and the ids dropped. Stroke width is left to the root so `weight` works.

   Usage: node scripts/gen-icons.mjs            (write)
          node scripts/gen-icons.mjs --check    (exit 1 if the file is stale)
          node scripts/gen-icons.mjs --all > x  (every name, one per line) */
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const listFile = path.join(root, "components/icons/icons.json");
const outFile = path.join(root, "components/icons/atlas.generated.ts");
const arg = process.argv[2];

const names = arg === "--all" ? null : JSON.parse(fs.readFileSync(listFile, "utf8"));

// Bundle a tiny renderer (the package is ESM in a .js file, which plain node won't load).
const entry = `
  import * as Atlas from "@vectoricons/atlas-icons-react";
  import { createElement } from "react";
  import { renderToStaticMarkup } from "react-dom/server";
  export const all = Object.keys(Atlas);
  export const render = (n) => Atlas[n] ? renderToStaticMarkup(createElement(Atlas[n], { weight: "medium" })) : null;
`;
const tmp = path.join(root, "node_modules/.cache/gen-icons/render.mjs");
fs.mkdirSync(path.dirname(tmp), { recursive: true });
await build({ stdin: { contents: entry, resolveDir: root }, bundle: true, platform: "node", format: "esm", outfile: tmp, logLevel: "error", external: ["react", "react-dom", "react-dom/server"] });
const { all, render } = await import(pathToFileURL(tmp).href);

if (arg === "--all") {
  console.log(all.join("\n"));
  process.exit(0);
}

const toAttr = (prop) => prop.trim();
function clean(name, svg) {
  const rules = {};
  for (const [, cls, body] of svg.matchAll(/\.([\w-]+)\{([^}]*)\}/g)) {
    rules[cls] = body.split(";").filter(Boolean).map((d) => d.split(":").map((x) => x.trim()));
  }
  let inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "").replace(/<defs>[\s\S]*?<\/defs>/, "");
  inner = inner.replace(/ class="([^"]+)"/g, (_, classes) =>
    classes.split(/\s+/).flatMap((c) => rules[c] ?? []).map(([k, v]) => ` ${toAttr(k)}="${v}"`).join(""),
  );
  inner = inner.replace(/ (id|data-name)="[^"]*"/g, "");
  // The root <svg> (createIcon) already sets these; repeating them per element only adds bytes.
  inner = inner.replace(/ fill="none"| stroke="currentColor"| stroke-miterlimit="10"/g, "");
  if (/ id=|<style|class=/.test(inner)) throw new Error(`${name}: could not clean markup`);
  return inner;
}

const missing = names.filter((n) => !all.includes(n));
if (missing.length) {
  console.error(`Not in Atlas: ${missing.join(", ")}`);
  process.exit(1);
}

const body = names
  .slice()
  .sort()
  .map((n) => `export const ${n}Icon = /*#__PURE__*/ createIcon("${n}", ${JSON.stringify(clean(n, render(n)))});`)
  .join("\n");
const file = `/* Generated by scripts/gen-icons.mjs from Atlas Icons (ISC). Do not edit.
   Add a name to components/icons/icons.json and run \`npm run icons\`. */
import { createIcon } from "./createIcon";

${body}
`;

if (arg === "--check") {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (current !== file) {
    console.error("components/icons/atlas.generated.ts is stale: run npm run icons");
    process.exit(1);
  }
} else {
  fs.writeFileSync(outFile, file);
  console.log(`${names.length} icons → ${path.relative(root, outFile)}`);
}
